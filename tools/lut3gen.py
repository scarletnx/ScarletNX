"""lut3gen.py OUT [--check]: writes the Sail of every truth table of three inputs (src/nx/gpu/shader/sail/lut3.sail),
each the shortest straight-line program of AND, OR, XOR and NOT of the inputs that computes it.

A table is a byte: its bit 4x + 2y + z is the result for those bits of x, y and z, so x is 0xf0, y 0xcc and z 0xaa. The
search goes breadth first over the sets of values computed so far, one operation a step (each value made once, as a
program's steps are), up to six steps; for each table the first program that makes it, by fewest operations, then
fewest NOTs, then the first found. With --check, OUT must already be what it writes (the lut3_sail_current test)."""
import sys

X, Y, Z = 0xf0, 0xcc, 0xaa
MAX_STEPS = 6


def search():
    best = {X: (0, 0, []), Y: (0, 0, []), Z: (0, 0, []), 0x00: (0, 0, None), 0xff: (0, 0, None)}
    # a state: the values made (inputs first), and the program that made them; deduplicated by its set of values
    frontier = {frozenset((X, Y, Z)): ((X, Y, Z), [])}
    for step in range(1, MAX_STEPS + 1):
        nxt = {}
        for values, program in frontier.values():
            nots = sum(1 for op in program if op[0] == 'not')
            candidates = []
            for i, a in enumerate(values):
                candidates.append(('not', i, None, ~a & 0xff))
                for j in range(i + 1, len(values)):
                    b = values[j]
                    candidates.append(('and', i, j, a & b))
                    candidates.append(('or', i, j, a | b))
                    candidates.append(('xor', i, j, a ^ b))
            for op, i, j, v in candidates:
                if v in values:
                    continue
                prog = program + [(op, i, j)]
                cost = (step, nots + (op == 'not'))
                if v not in best or cost < best[v][:2]:
                    best[v] = (cost[0], cost[1], prog)
                key = frozenset(values + (v,))
                if key not in nxt:
                    nxt[key] = (values + (v,), prog)
        frontier = nxt
        if len(best) == 256:
            break
    return best


def sail_expr(lut, entry, boolean):
    """the program as a Sail block: each step a let, the last the value"""
    names = ['x', 'y', 'z']
    if entry[2] is None:
        return ('true' if boolean else '0xffffffff') if lut == 0xff else ('false' if boolean else '0x00000000')
    if not entry[2]:
        return names[{X: 0, Y: 1, Z: 2}[lut]]
    lines = []
    for k, (op, i, j) in enumerate(entry[2]):
        a, b = names[i], names[j] if j is not None else None
        if op == 'not':
            e = f'not_bool({a})' if boolean else f'not_vec({a})'
        elif op == 'and':
            e = f'{a} & {b}'
        elif op == 'or':
            e = f'{a} | {b}'
        else:
            e = f'{a} != {b}' if boolean else f'EOR({a}, {b})'
        name = f't{k}'
        names.append(name)
        lines.append(f'let {name} = {e};')
    if len(lines) == 1:
        return lines[0].split(' = ', 1)[1].rstrip(';')
    return '{ ' + ' '.join(lines) + f' {names[-1]} ' + '}'


def main():
    out = sys.argv[1]
    best = search()
    missing = [v for v in range(256) if v not in best]
    if missing:
        sys.exit(f'lut3gen: no program of {MAX_STEPS} steps for {len(missing)} tables')
    total = sum(best[v][0] for v in range(256))
    text = ['/* SPDX-License-Identifier: GPL-3.0-or-later */',
            '/* Copyright 2026 the ScarletNX contributors */',
            '/* Generated by tools/lut3gen.py: do not edit. Every truth table of three inputs as the shortest straight-line',
            f'   program of AND, OR, XOR and NOT of the inputs ({total} operations for the 256, fewest NOTs among the',
            '   shortest): x is the 0xf0 input, y 0xcc and z 0xaa, and bit 4x + 2y + z of lut the result for those bits.',
            '   gpu.sail\'s Lut3 (of a word\'s bits) and Lut3Bool (of bools), which LOP3 and PLOP3 take; tests/shader_sail_sm86.c',
            '   checks every table whole */', '']
    for boolean in (False, True):
        t = 'bool' if boolean else 'bits(32)'
        name = 'Lut3Bool' if boolean else 'Lut3'
        text.append(f'function {name}(lut : bits(8), x : {t}, y : {t}, z : {t}) -> {t} =')
        text.append('    match lut {')
        for v in range(256):  # sailgen wants a match to end with _: 0xff's
            pattern = '_' if v == 0xff else f'0x{v:02x}'
            text.append(f'        {pattern} => {sail_expr(v, best[v], boolean)},')
        text[-1] = text[-1].rstrip(',')
        text.append('    }')
        text.append('')
    data = '\n'.join(text)
    if '--check' in sys.argv:
        if open(out).read() != data:
            sys.exit(f'lut3gen: {out} is not what tools/lut3gen.py writes: run it')
        return
    open(out, 'w').write(data)
    print(f'{total} operations for the 256 tables (the minterms\' sum of products: 4608)')


main()
