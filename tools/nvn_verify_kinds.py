"""Generates src/nx/gpu/nvn/nvn_verify_kinds.inc: for each NVN function gpu/nvn/nvn.hook implements, what each of its
arguments is to nvn_verify's shadow driver (gpu/nvn/nvn_verify.c), from the argument types of its prototype in
nvn.hook (tools/hook_spec.py), in the types of src/nx/gpu/nvn/nvn.h.

    tools/nvn_verify_kinds.py            # writes the file
    tools/nvn_verify_kinds.py --check    # exits 1 when the file is not what this script writes (a ctest)

The kinds, one letter per argument (nvn_verify.h has the same list):
  v  a value in an integer register (an integer, an enum, a GPU address)
  F  a float, in a vector register
  o  a pointer to an object the game keeps at one address (device, queue, pool, buffer, texture...): the shadow's
  O  an array of such pointers, as many as the integer argument before it
  s  a pointer to a builder or a state object, which the game can copy by value: the shadow's copy of its state
  S  an array of state objects, as many as the integer argument before it
  T  an array of pointers to state objects (texture views), as many as the integer argument before it
  m  memory the driver writes (pool storage, queue memory, control memory), its size the argument after it
  r  an array of mapping requests (they hold pool and texture pointers), as many as the integer argument before it
  p  a pointer the driver only reads (data, a label, command handles)
  w  a pointer the driver writes a result to
  f  a function pointer
"""

import os
import re
import sys

import hook_spec

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NVN_H = os.path.join(ROOT, 'src/nx/gpu/nvn/nvn.h')
HOOK = os.path.join(ROOT, 'src/nx/gpu/nvn/nvn.hook')
OUT = os.path.join(ROOT, 'src/nx/gpu/nvn/nvn_verify_kinds.inc')

OBJECTS = {'NVNdevice', 'NVNqueue', 'NVNcommandBuffer', 'NVNmemoryPool', 'NVNbuffer', 'NVNtexture', 'NVNsampler',
           'NVNtexturePool', 'NVNsamplerPool', 'NVNprogram', 'NVNsync', 'NVNwindow', 'NVNevent'}
# the driver writes these memory arguments: each is followed by its size
MEMORY = {('nvnMemoryPoolBuilderSetStorage', 1), ('nvnQueueBuilderSetQueueMemory', 1),
          ('nvnCommandBufferAddControlMemory', 1)}
# a state object pointer after a count is an array of them
STATE_ARRAYS = {'nvnCommandBufferBindVertexAttribState', 'nvnCommandBufferBindVertexStreamState'}


def is_state(base):
    return base == 'NVNtextureView' or re.fullmatch(r'NVN\w+(Builder|State)', base) is not None


def kind(fn, i, arg, args):
    if (fn, i) in MEMORY:
        return 'm'
    if 'PFNNVN' in arg or '(*' in arg:
        return 'f'
    stars = arg.count('*')
    if not stars:
        return 'F' if arg in ('f32', 'f64') else 'v'
    base = re.sub(r'\bconst\b', '', arg).replace('*', ' ').split()[0]
    counted = i > 0 and '*' not in args[i - 1]
    if base in OBJECTS:
        return 'O' if stars > 1 else 'o'
    if is_state(base):
        if stars > 1:
            return 'T'
        return 'S' if fn in STATE_ARRAYS and counted else 's'
    if base == 'NVNmappingRequest':
        return 'r'
    if base in ('NVNtextureBuilder',):
        return 's'
    return 'p' if arg.startswith('const') or base == 'char' else 'w'


def generate():
    protos = hook_spec.prototypes(HOOK)
    types = hook_spec.header_types(NVN_H)
    rows = []
    for n in sorted(protos):
        ret, args, _ = protos[n]
        kinds = ''.join(kind(n, i, a, args) for i, a in enumerate(args))
        types_of = [re.sub(r'\bconst\b|\*', '', a).split()[0] if '*' in a and 'PFNNVN' not in a else '' for a in args]
        sizes = ', '.join(f'sizeof({t})' if k in 'osSTr' else '0' for k, t in zip(kinds, types_of)) or '0'
        ret = {'void': 0, 'addr': 'NVK_RET_ADDR', 'f32': 'NVK_RET_F32', 'f64': 'NVK_RET_F32', 'bool': 'NVK_RET_BOOL',
               'u64': 'NVK_RET_X64', 'i64': 'NVK_RET_X64'}.get(hook_spec.kind(ret, types), 'NVK_RET_X32')
        rows.append(f'    {{"{n}", "{kinds}", {ret}, {{{sizes}}}}},')
    head = ('/* SPDX-License-Identifier: GPL-3.0-or-later\n   Copyright 2026 the ScarletNX contributors */\n'
            '/* Generated by tools/nvn_verify_kinds.py from gpu/nvn/nvn.hook and nvn.h: do not edit. Each NVN '
            'function\n   nvn.hook implements, its arguments\' kinds (nvn_verify.h), its result and the bytes of each object or '
            'state they point to */\n')
    return head + '\n'.join(rows) + '\n'


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        same = os.path.exists(OUT) and open(OUT).read() == text
        if not same:
            print('nvn_verify_kinds.inc is stale: run tools/nvn_verify_kinds.py')
        return 0 if same else 1
    with open(OUT, 'w') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
