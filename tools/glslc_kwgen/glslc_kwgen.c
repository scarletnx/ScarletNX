/* glslc_kwgen: the perfect hash of glslc's keywords (src/glslc/builtins.c's glslc_keywords), written as
   glslc_keywords.inc for src/glslc/keywords.c when glslc is built. Hash and displace: the keywords go into buckets by
   the low bits of their glslc_hash, and each bucket, the fullest first, takes the first displacement that gives every
   keyword of it a slot of its own (glslc_keyword_slot). A lookup is then one slot and one compare. It is C99 and
   links only builtins.c, so a cross build builds it for the machine it runs on.

   Usage: glslc_kwgen OUT.inc (rewritten only when it changes) */
#include "glslc/internal.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_KEYWORDS     1024
#define MAX_DISPLACEMENT 65536u

static uint32_t hashes[MAX_KEYWORDS];
static uint16_t slots[MAX_KEYWORDS * 8];
static uint16_t displacements[MAX_KEYWORDS];
static int order[MAX_KEYWORDS], sizes[MAX_KEYWORDS];

static int by_size(const void* a, const void* b) {
    int x = *(const int*)a, y = *(const int*)b;
    return sizes[y] != sizes[x] ? sizes[y] - sizes[x] : x - y;
}

/* the layout of n keywords in slot_count slots and bucket_count buckets: 1, or 0 when a bucket finds no
   displacement */
static int place(uint32_t n, uint32_t slot_count, uint32_t bucket_count) {
    memset(slots, 0, sizeof slots);
    memset(displacements, 0, sizeof displacements);
    memset(sizes, 0, sizeof sizes);
    for (uint32_t i = 0; i < n; i++) sizes[hashes[i] & (bucket_count - 1)]++;
    for (uint32_t b = 0; b < bucket_count; b++) order[b] = (int)b;
    qsort(order, bucket_count, sizeof order[0], by_size);
    for (uint32_t o = 0; o < bucket_count && sizes[order[o]]; o++) {
        uint32_t b = (uint32_t)order[o], d;
        for (d = 0; d < MAX_DISPLACEMENT; d++) {
            uint32_t taken[64], ntaken = 0, ok = 1;
            for (uint32_t i = 0; i < n && ok; i++) {
                if ((hashes[i] & (bucket_count - 1)) != b) continue;
                uint32_t s = glslc_keyword_slot(hashes[i], d, slot_count - 1);
                if (slots[s]) ok = 0;
                for (uint32_t t = 0; t < ntaken && ok; t++) ok = taken[t] != s;
                if (ok && ntaken < 64) taken[ntaken++] = s;
            }
            if (ok) break;
        }
        if (d == MAX_DISPLACEMENT) return 0;
        displacements[b] = (uint16_t)d;
        for (uint32_t i = 0; i < n; i++)
            if ((hashes[i] & (bucket_count - 1)) == b)
                slots[glslc_keyword_slot(hashes[i], d, slot_count - 1)] = (uint16_t)(i + 1);
    }
    return 1;
}

int main(int argc, char** argv) {
    uint32_t n = glslc_keyword_count, longest = 0, slot_count, bucket_count = 0;
    if (argc != 2) {
        fprintf(stderr, "usage: glslc_kwgen OUT.inc\n");
        return 2;
    }
    if (n >= MAX_KEYWORDS) {
        fprintf(stderr, "glslc_kwgen: %u keywords, more than the %u it takes\n", n, MAX_KEYWORDS - 1);
        return 1;
    }
    for (uint32_t i = 0; i < n; i++) {
        char padded[256] = {0}; /* glslc_hash reads past the text */
        uint32_t len = glslc_keywords[i].len;
        if (len >= sizeof padded - 8 || len != strlen(glslc_keywords[i].name)) {
            fprintf(stderr, "glslc_kwgen: keyword %s has a length of %u\n", glslc_keywords[i].name, len);
            return 1;
        }
        memcpy(padded, glslc_keywords[i].name, len);
        hashes[i] = glslc_hash(padded, len);
        if (len > longest) longest = len;
        for (uint32_t k = 0; k < i; k++)
            if (hashes[k] == hashes[i]) {
                fprintf(stderr, "glslc_kwgen: %s and %s have one hash, which no displacement parts\n",
                        glslc_keywords[k].name, glslc_keywords[i].name);
                return 1;
            }
    }
    /* the fewest slots, at least twice the keywords, then the fewest buckets, that a layout fits */
    for (slot_count = 2; slot_count < 2 * n; slot_count *= 2) {}
    for (;; slot_count *= 2) {
        if (slot_count > MAX_KEYWORDS * 8) {
            fprintf(stderr, "glslc_kwgen: no layout of the %u keywords\n", n);
            return 1;
        }
        bucket_count = 8;
        while (bucket_count <= slot_count && !place(n, slot_count, bucket_count)) bucket_count *= 2;
        if (bucket_count <= slot_count) break;
    }
    /* the file, written only when it changes, so keywords.c compiles again only then */
    char* text = malloc(65536 + (size_t)slot_count * 8);
    if (!text) return 1;
    size_t w = 0;
    w += (size_t)sprintf(text + w,
                         "/* Generated by tools/glslc_kwgen from src/glslc/builtins.c's glslc_keywords: change the "
                         "table, not this file */\n#define GLSLC_KEYWORD_SLOTS   %uu\n"
                         "#define GLSLC_KEYWORD_BUCKETS %uu\n"
                         "#define GLSLC_KEYWORD_LONGEST %uu\n/* each bucket's displacement */\n"
                         "static const uint16_t glslc_keyword_displacements[%u] = {",
                         slot_count, bucket_count, longest, bucket_count);
    for (uint32_t b = 0; b < bucket_count; b++)
        w += (size_t)sprintf(text + w, "%s%u,", b % 16 ? " " : "\n    ", displacements[b]);
    w += (size_t)sprintf(text + w, "\n};\n/* each slot's keyword, its row in glslc_keywords plus one, 0 for none */\n"
                                   "static const uint16_t glslc_keyword_slots[%u] = {", slot_count);
    for (uint32_t s = 0; s < slot_count; s++)
        w += (size_t)sprintf(text + w, "%s%u,", s % 16 ? " " : "\n    ", slots[s]);
    w += (size_t)sprintf(text + w, "\n};\n");
    FILE* f = fopen(argv[1], "rb");
    if (f) {
        char* old = malloc(w + 1);
        size_t got = old ? fread(old, 1, w + 1, f) : 0;
        int same = old && got == w && !memcmp(old, text, w);
        free(old);
        fclose(f);
        if (same) return 0;
    }
    f = fopen(argv[1], "wb");
    if (!f || fwrite(text, 1, w, f) != w || fclose(f)) {
        fprintf(stderr, "glslc_kwgen: cannot write %s\n", argv[1]);
        return 1;
    }
    free(text);
    return 0;
}
