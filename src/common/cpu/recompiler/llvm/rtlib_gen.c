/* Build-time helper for the LLVM backend's runtime library (rtlib.c):
     snx-rtlib-gen interp OUT       the interpreter of the templates' C, for tests (tests/ldr_interp.c): no module or
                                    runtime has one any more
     snx-rtlib-gen embed IN OUT SYM the compiled rtlib object as a C array the recompiler links into each module */
#include "common/cpu/aarch64/a64.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static char* capture(void (*emit)(FILE*, int), int mode, size_t* size) {
    FILE* f = tmpfile();
    char* text;
    long n;
    if (!f) return NULL;
    emit(f, mode);
    n = ftell(f);
    if (n < 0 || fseek(f, 0, SEEK_SET)) {
        fclose(f);
        return NULL;
    }
    text = (char*)malloc((size_t)n + 1);
    if (text && fread(text, 1, (size_t)n, f) != (size_t)n) {
        free(text);
        text = NULL;
    }
    if (text) text[n] = 0;
    fclose(f);
    *size = (size_t)n;
    return text;
}

static int interp(const char* path) {
    static const char hidden[] = "static void snx_interp(";
    char *text, *at;
    size_t size;
    FILE* out = fopen(path, "wb");
    if (!out) return 1;
    fputs("/* generated by snx-rtlib-gen from a64_templates.inc */\n", out);
    text = capture(snx_a64_interp, 0, &size);
    if (!text || !(at = strstr(text, hidden))) return 1;
    /* external linkage: the module descriptor the LLVM backend emits refers to it */
    fwrite(text, 1, (size_t)(at - text), out);
    fputs(at + strlen("static "), out);
    free(text);
    return fclose(out) != 0;
}

static int embed(const char* input, const char* path, const char* symbol) {
    FILE *in = fopen(input, "rb"), *out;
    int c;
    unsigned long n = 0;
    if (!in) return 1;
    out = fopen(path, "wb");
    if (!out) {
        fclose(in);
        return 1;
    }
    fprintf(out, "/* generated by snx-rtlib-gen from %s */\nconst unsigned char %s[] = {", input, symbol);
    for (; (c = fgetc(in)) != EOF; ++n) fprintf(out, "%s%u", !n ? "\n" : n % 24 ? "," : ",\n", (unsigned)c);
    fprintf(out, "\n};\nconst unsigned long %s_size = %luUL;\n", symbol, n);
    fclose(in);
    return fclose(out) != 0;
}

int main(int argc, char** argv) {
    if (argc == 3 && !strcmp(argv[1], "interp")) return interp(argv[2]);
    if (argc == 5 && !strcmp(argv[1], "embed")) return embed(argv[2], argv[3], argv[4]);
    fputs("usage: snx-rtlib-gen interp OUT | embed IN OUT SYMBOL\n", stderr);
    return 2;
}
