"""Compile the shaders of the on-screen controls and the game's menu (src/nx/gpu/vk/shaders/ui.*) into ui_spv.h.

Needs a GLSL compiler (glslc, or glslangValidator as the build's shaders use) and spirv-val; --check needs neither: it
only compares the sources' hash with the one the header holds.
"""

import argparse
import hashlib
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

SHADERS = [('snx_ui_vs_spv', 'ui.vert', 'vert'), ('snx_ui_fs_spv', 'ui.frag', 'frag')]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail when the header was not made from these sources')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    folder = root / 'src/nx/gpu/vk/shaders'
    header = root / 'src/nx/gpu/vk/ui_spv.h'
    # the bytes as the repository holds them: a Windows checkout turns the line ends into CR LF
    lf = lambda path: path.read_bytes().replace(b'\r\n', b'\n')
    digest = hashlib.sha256(lf(Path(__file__)))
    for _, name, _ in SHADERS:
        digest.update(lf(folder / name))
    digest = digest.hexdigest()
    if args.check:
        if f'sources {digest}' not in header.read_text():
            raise SystemExit('ui_spv.h is not what src/nx/gpu/vk/shaders makes: run scripts/build-ui-shaders.py')
        return
    text = f"""/* SPDX-License-Identifier: GPL-3.0-or-later
   Copyright 2026 the ScarletNX contributors
   Generated by scripts/build-ui-shaders.py from src/nx/gpu/vk/shaders. Do not edit.
   sources {digest} */
#ifndef SNX_UI_SPV_H
#define SNX_UI_SPV_H
#include <stdint.h>
// clang-format off
"""
    with tempfile.TemporaryDirectory() as temporary:
        for array, name, stage in SHADERS:
            spv = Path(temporary) / f'{name}.spv'
            if shutil.which('glslc'):
                command = [
                    'glslc',
                    f'-fshader-stage={stage}',
                    '--target-env=vulkan1.3',
                    '-O',
                    str(folder / name),
                    '-o',
                    str(spv),
                ]
            else:  # the build's own compiler: glslangValidator (-Os is spirv-opt's size pass, as -O is glslc's)
                command = [
                    'glslangValidator',
                    '-V',
                    '--target-env',
                    'vulkan1.3',
                    '-Os',
                    '-o',
                    str(spv),
                    str(folder / name),
                ]
            subprocess.run(command, check=True)
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.3', str(spv)], check=True)
            data = spv.read_bytes()
            words = struct.unpack(f'<{len(data) // 4}I', data)
            text += f'static const uint32_t {array}[] = {{\n'
            for i in range(0, len(words), 8):
                text += '    ' + ', '.join(f'0x{value:08x}u' for value in words[i : i + 8]) + ',\n'
            text += '};\n'
    text += '// clang-format on\n#endif\n'
    header.write_text(text)


if __name__ == '__main__':
    main()
