"""gen_dsp_aac_fixture.py --ffmpeg PATH [--output PATH]: writes tests/support/dsp_aac_fixture.h, the AAC frames that
tests/3ds_dsp.c sends to the DSP's binary pipe. The frames are FFmpeg's AAC encoder output for 16-bit sine waves that
this script synthesizes itself. It reads no recording and no game file. Run it with `python -I`."""

import argparse
import math
import os
import struct
import subprocess
import tempfile

SECONDS = 0.25
AMPLITUDE = 0.5
ADTS_HEADER_SIZE = 7


def sine_pcm(rate, freqs):
    count = round(SECONDS * rate)
    channels = [[round(AMPLITUDE * 32767 * math.sin(2 * math.pi * f * n / rate)) for n in range(count)] for f in freqs]
    samples = [value for frame in zip(*channels) for value in frame]
    return struct.pack("<%dh" % len(samples), *samples)


def is_adts_header(head):
    sync = head[0] == 0xFF and (head[1] & 0xF0) == 0xF0
    layer_zero = (head[1] & 0x06) == 0
    one_raw_block = (head[6] & 0x03) == 0
    return sync and layer_zero and one_raw_block


def split_adts(data):
    frames = []
    at = 0
    while at < len(data):
        head = data[at:at + ADTS_HEADER_SIZE]
        if len(head) < ADTS_HEADER_SIZE or not is_adts_header(head):
            raise ValueError("no ADTS header at byte %d" % at)
        length = ((head[3] & 0x03) << 11) | (head[4] << 3) | (head[5] >> 5)
        if length < ADTS_HEADER_SIZE or at + length > len(data):
            raise ValueError("ADTS frame of %d bytes at byte %d does not fit" % (length, at))
        frames.append(data[at:at + length])
        at += length
    return frames


def encode(ffmpeg, workdir, rate, channels, freqs):
    stem = os.path.join(workdir, "sine_%d_%dch" % (rate, channels))
    with open(stem + ".s16le", "wb") as f:
        f.write(sine_pcm(rate, freqs))
    subprocess.run([ffmpeg, "-hide_banner", "-loglevel", "error", "-f", "s16le", "-ar", str(rate), "-ac", str(channels),
                    "-i", stem + ".s16le", "-c:a", "aac", "-b:a", "128k", "-f", "adts", stem + ".aac"], check=True)
    with open(stem + ".aac", "rb") as f:
        return split_adts(f.read())


def first_frames(frames, count, what):
    if len(frames) < count:
        raise SystemExit("%s: the encoder wrote %d frames, need %d" % (what, len(frames), count))
    return frames[:count]


def c_array(name, comment, data):
    lines = ["/* %s, %d bytes */" % (comment, len(data)), "static const unsigned char %s[] = {" % name]
    rows = (len(data) + 18) // 19
    per_row = (len(data) + rows - 1) // rows
    for at in range(0, len(data), per_row):
        lines.append("    " + ", ".join("0x%02x" % byte for byte in data[at:at + per_row]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Write the AAC fixture header of tests/3ds_dsp.c.")
    parser.add_argument("--ffmpeg", required=True, help="an ffmpeg executable with the aac encoder")
    here = os.path.dirname(os.path.abspath(__file__))
    parser.add_argument("--output", default=os.path.join(here, "dsp_aac_fixture.h"),
                        help="the header to write (default: beside this script)")
    args = parser.parse_args()
    workdir = tempfile.mkdtemp(prefix="dsp_aac_fixture_")
    stereo = first_frames(encode(args.ffmpeg, workdir, 48000, 2, (1000, 1500)), 3, "48000 Hz stereo")
    mono = {}
    for rate in (48000, 44100, 8000, 96000):
        mono[rate] = first_frames(encode(args.ffmpeg, workdir, rate, 1, (1000,)), 3, "%d Hz mono" % rate)[2]
    arrays = [
        c_array("dsp_aac_stereo_48k", "48000 Hz stereo, the first three frames of 0.25 s, 1000 Hz left, 1500 Hz right",
                b"".join(stereo)),
        c_array("dsp_aac_mono_48k", "48000 Hz mono, the third frame of 0.25 s at 1000 Hz", mono[48000]),
        c_array("dsp_aac_mono_44k1", "44100 Hz mono, the third frame of 0.25 s at 1000 Hz", mono[44100]),
        c_array("dsp_aac_mono_8k", "8000 Hz mono, the third frame of 0.25 s at 1000 Hz", mono[8000]),
        c_array("dsp_aac_mono_96k", "96000 Hz mono, the third frame of 0.25 s at 1000 Hz", mono[96000]),
    ]
    prologue = "\n".join([
        "/* SPDX-License-Identifier: GPL-3.0-or-later",
        "   Copyright 2026 the ScarletNX contributors */",
        "/* Generated by tests/support/gen_dsp_aac_fixture.py from synthesized sine waves; do not edit. */",
        "#ifndef SNX_TEST_DSP_AAC_FIXTURE_H",
        "#define SNX_TEST_DSP_AAC_FIXTURE_H",
        "",
    ])
    with open(args.output, "w", encoding="ascii", newline="\n") as f:
        f.write(prologue + "\n".join(arrays) + "\n#endif\n")
    print("wrote %s" % args.output)


if __name__ == "__main__":
    main()
