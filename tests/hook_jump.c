static size_t encode(const char* arch, u8* out, u64 at, u64 to) {
    if (!strcmp(arch, "x86_64")) return snx_hook_jump_x86_64(out, at, to);
    if (!strcmp(arch, "aarch64")) return snx_hook_jump_aarch64(out, at, to);
    if (!strcmp(arch, "ppc64le-v2")) return snx_hook_jump_ppc64(out, to, 0, 0);
    if (!strcmp(arch, "ppc64be-v2")) return snx_hook_jump_ppc64(out, to, 0, 1);
    if (!strcmp(arch, "ppc64be-v1")) return snx_hook_jump_ppc64(out, to, 1, 1);
    if (!strcmp(arch, "s390x")) return snx_hook_jump_s390x(out, at, to);
    if (!strcmp(arch, "mips64el")) return snx_hook_jump_mips64(out, to, 0);
    if (!strcmp(arch, "mips64")) return snx_hook_jump_mips64(out, to, 1);
    if (!strcmp(arch, "riscv64")) return snx_hook_jump_riscv64(out, at, to);
    if (!strcmp(arch, "loongarch64")) return snx_hook_jump_loongarch64(out, at, to);
    if (!strcmp(arch, "ia64")) return snx_hook_jump_ia64(out, at, to);
    fprintf(stderr, "no encoder named %s\n", arch);
    exit(1);
}

int main(void) {
    size_t i, n, checks = 0;
    for (i = 0; i < sizeof rows / sizeof rows[0]; i++) {
        u8 out[SNX_HOOK_JUMP_MAX];
        memset(out, 0xEE, sizeof out);
        n = encode(rows[i].arch, out, rows[i].at, rows[i].to);
        if (n != rows[i].n || memcmp(out, rows[i].bytes, n)) {
            size_t k;
            fprintf(stderr, "%s from %llx to %llx: %zu bytes, expected %zu:", rows[i].arch,
                    (unsigned long long)rows[i].at, (unsigned long long)rows[i].to, n, rows[i].n);
            for (k = 0; k < n; k++) fprintf(stderr, " %02x", out[k]);
            fputc('\n', stderr);
            return 1;
        }
        checks++;
    }
    /* out of IA-64's reach: a bundle not 16-byte aligned */
    {
        u8 out[SNX_HOOK_JUMP_MAX];
        if (snx_hook_jump_ia64(out, 0x1008, 0x2000)) return fprintf(stderr, "ia64: a bundle from 1008\n"), 1;
        checks++;
    }
    printf("hook_jump: %zu checks passed, the host's jump is %s's\n", checks,
           snx_hook_jump_host() ? snx_hook_jump_host() : "no architecture");
    return 0;
}
