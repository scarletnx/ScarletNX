/* the instruction that makes id, 0 for none */
static u32 made_at(const u32* w, size_t bytes, u32 id) {
    for (u32 i = 5; i < bytes / 4; i += w[i] >> 16) {
        u32 op = w[i] & 0xffff, len = w[i] >> 16;
        int typed = op == 59 || op == 61 || op == 65 || op == 80 || op == 81 || op == 103 || op == 104 || op == 124 ||
                    op == 128 || op == 132 || op == 134 || op == 135 || op == 194 || op == 199;
        if (typed && len >= 3 && w[i + 2] == id) return i;
    }
    return 0;
}
/* the Offset of the last member of the structure behind the module's PushConstant variable, and how many there are */
static u32 push_member_offset(const u32* w, size_t bytes, u32* push_vars) {
    u32 ptr = 0, block = 0, last = 0, offset = 0;
    *push_vars = 0;
    for (u32 i = 5; i < bytes / 4; i += w[i] >> 16)
        if ((w[i] & 0xffff) == 59 && w[i + 3] == 9) {
            ptr = w[i + 1];
            ++*push_vars;
        }
    for (u32 i = 5; i < bytes / 4; i += w[i] >> 16)
        if ((w[i] & 0xffff) == 32 && w[i + 1] == ptr) block = w[i + 3];
    for (u32 i = 5; i < bytes / 4; i += w[i] >> 16)
        if ((w[i] & 0xffff) == 30 && w[i + 1] == block) last = (w[i] >> 16) - 3;
    for (u32 i = 5; i < bytes / 4; i += w[i] >> 16)
        if ((w[i] & 0xffff) == 72 && w[i + 1] == block && w[i + 2] == last && w[i + 3] == 35) offset = w[i + 4];
    return offset;
}
/* the module valid for env by the validator, where there is one */
static void validate(const char* validator, const char* env, const u32* w, size_t bytes) {
    if (!validator) return;
    FILE* f = fopen("gvk_spirv_scaled.spv", "wb");
    assert(f && fwrite(w, 1, bytes, f) == bytes);
    fclose(f);
    char cmd[1024];
    snprintf(cmd, sizeof cmd, "\"%s\" --target-env %s gvk_spirv_scaled.spv", validator, env);
    assert(system(cmd) == 0);
    remove("gvk_spirv_scaled.spv");
}
/* the size query's result id: the division of the query's own, its width and height divided and a third kept */
static void check_divided(const u32* out, size_t bytes, u32 result, u32 count) {
    u32 c = made_at(out, bytes, result);
    assert(c && (out[c] & 0xffff) == 80 && out[c] >> 16 == 3 + count);
    u32 query = 0;
    for (u32 k = 0; k < count; k++) {
        u32 part = made_at(out, bytes, out[c + 3 + k]);
        assert(part && (k < 2) == ((out[part] & 0xffff) == 135)); /* SDiv of an extract of the query, or the extract */
        u32 x = k < 2 ? made_at(out, bytes, out[part + 3]) : part;
        assert(x && (out[x] & 0xffff) == 81 && out[x + 4] == k);
        u32 q = made_at(out, bytes, out[x + 3]);
        assert(q && ((out[q] & 0xffff) == 103 || (out[q] & 0xffff) == 104));
        assert(!query || query == q);
        query = q;
    }
}

/* the ids of the module that mend gave NonUniform, and whether they are exactly these */
static int marked(const u32* w, size_t bytes, size_t n, const u32* ids) {
    size_t found = 0;
    for (size_t i = 0; i < n; i++) found += COUNT(w, bytes, OP_DECORATE, ids[i], NON_UNIFORM) == 1;
    size_t all = 0;
    for (u32 i = 5; i < bytes / 4; i += w[i] >> 16)
        all += (w[i] & 0xffff) == OP_DECORATE && (w[i] >> 16) == 3 && w[i + 2] == NON_UNIFORM;
    return found == n && all == n;
}
